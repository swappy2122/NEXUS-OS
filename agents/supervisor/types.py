"""Supervisor type definitions for NEXUS OS.

Data contracts for the orchestration layer:

* **IntentClassification** — parsed understanding of what the user wants
* **SubIntent**            — a decomposed piece of a multi-agent request
* **ExecutionStep**        — single unit of work inside a plan
* **ExecutionPlan**        — the complete work plan handed to the executor
* **PipelineResult**       — aggregated outcome of plan execution

These models are Pydantic ``BaseModel`` subclasses — serialisable,
validatable, and safe to log or return via the API.
"""

from __future__ import annotations

from enum import Enum
from typing import Any
from uuid import uuid4

from pydantic import BaseModel, Field

from agents.types import AgentResult


# ── Enums ────────────────────────────────────────────────────────────────

class StepStatus(str, Enum):
    """Lifecycle state of a single execution step."""

    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    SKIPPED = "skipped"


class ExecutionMode(str, Enum):
    """How the executor should process the steps in a plan."""

    SINGLE = "single"          # one agent, one step
    SEQUENTIAL = "sequential"  # steps run in dependency order
    PARALLEL = "parallel"      # independent steps run concurrently


# ── Intent classification ────────────────────────────────────────────────

class SubIntent(BaseModel):
    """A decomposed piece of a multi-agent request.

    Produced by routing strategies (particularly LLM-based) that can
    split a complex request into discrete sub-tasks.
    """

    description: str
    target_agent: str
    depends_on: list[int] = Field(
        default_factory=list,
        description="Indices of prior sub-intents that must complete first",
    )
    parameters: dict[str, Any] = Field(default_factory=dict)


class StructuredAction(BaseModel):
    """A concrete, structured action / tool invocation produced by the LLM.

    Represents a validated instruction ready for an agent to execute.
    """

    step_id: int = 0
    agent_name: str
    tool_name: str
    arguments: dict[str, Any] = Field(default_factory=dict)
    depends_on: list[int] = Field(
        default_factory=list,
        description="step_ids of prior actions this action depends on",
    )
    thought: str = Field(
        default="",
        description="LLM reasoning for why this action and capability were selected",
    )


class ActionValidationResult(BaseModel):
    """Outcome of validating a structured action before execution."""

    is_valid: bool
    error: str | None = None
    sanitized_arguments: dict[str, Any] = Field(default_factory=dict)


class LLMPlanOutput(BaseModel):
    """Structured JSON output produced by the Supervisor LLM."""

    thought: str = ""
    capabilities_required: list[str] = Field(default_factory=list)
    actions: list[StructuredAction] = Field(default_factory=list)
    direct_response: str = Field(
        default="",
        description="Direct conversational answer when no tool execution is required",
    )


class IntentClassification(BaseModel):
    """Result of classifying a user's raw intent.

    Produced by a :class:`~agents.supervisor.strategies.RoutingStrategy`,
    consumed by the :class:`~agents.supervisor.planner.ExecutionPlanner`.
    """

    raw_intent: str
    primary_agent: str | None = None
    agent_scores: dict[str, float] = Field(
        default_factory=dict,
        description="Per-agent relevance scores from the routing strategy",
    )
    confidence: float = 0.0
    requires_multi_agent: bool = False
    sub_intents: list[SubIntent] = Field(default_factory=list)
    actions: list[StructuredAction] = Field(
        default_factory=list,
        description="Concrete structured tool actions generated by the LLM",
    )
    thought: str = ""
    direct_response: str = ""
    metadata: dict[str, Any] = Field(default_factory=dict)


# ── Execution plan ──────────────────────────────────────────────────────

class ExecutionStep(BaseModel):
    """A single unit of work within an ExecutionPlan."""

    step_id: int
    agent_name: str
    intent: str
    parameters: dict[str, Any] = Field(default_factory=dict)
    depends_on: list[int] = Field(
        default_factory=list,
        description="step_ids that must complete successfully before this runs",
    )
    action: StructuredAction | None = Field(
        default=None,
        description="The structured action associated with this step",
    )
    status: StepStatus = StepStatus.PENDING
    result: AgentResult | None = None


class ExecutionPlan(BaseModel):
    """A concrete plan of steps to execute for a user request.

    Built by the :class:`~agents.supervisor.planner.ExecutionPlanner`,
    consumed by the :class:`~agents.supervisor.executor.PlanExecutor`.
    """

    plan_id: str = Field(default_factory=lambda: uuid4().hex[:12])
    mode: ExecutionMode = ExecutionMode.SINGLE
    steps: list[ExecutionStep] = Field(default_factory=list)
    original_intent: str = ""
    classification: IntentClassification | None = None
    metadata: dict[str, Any] = Field(default_factory=dict)


# ── Pipeline result ─────────────────────────────────────────────────────

class PipelineResult(BaseModel):
    """Aggregated result of executing an entire plan.

    Carries the combined output, per-step details, and error list.
    """

    plan_id: str = ""
    success: bool = True
    steps: list[ExecutionStep] = Field(default_factory=list)
    final_output: str = ""
    errors: list[str] = Field(default_factory=list)
    total_duration_ms: float = 0.0
    agents_used: list[str] = Field(default_factory=list)
